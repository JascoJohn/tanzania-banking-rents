"""FinScope Tanzania microdata and data map (prompt 01 section 3.7; blueprint §6, ch. 1-2 and the cross-cutting
question on access and switching costs). Profiling only; no analysis in prompt 01.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

import pandas as pd

from tzbank.config import find_root, path
from tzbank.io import write_csv, write_text

log = logging.getLogger(__name__)

# Keyword groups for the variables relevant to the blueprint (labels and names, case-insensitive).
TOPICS: dict[str, str] = {
    "banks": r"\bbank|BANKED|serv\d",
    "mobile_money": r"mobile money|\bMM\b|mob\d|wallet|M-PAWA|lipa namba",
    "savings": r"\bsav(e|ing)|put money aside|^f_",
    "borrowing": r"borrow|loan|lender|credit|^g_",
    "access_strand": r"strand|FORMAL|INFORMAL",
}
WEIGHT_PATTERN = re.compile(r"weight|_wt$|^wt_|wgt", re.I)


def read_datamap(file: Path | None = None) -> pd.DataFrame:
    """Variables sheet joined to value labels: variable, position, label, measurement_level, value_labels."""
    file = file or path("finscope_datamap")
    v = pd.read_excel(file, sheet_name="Variables", header=1, dtype=object)
    v = v[v["Variable"].notna()].copy()
    vl = pd.read_excel(file, sheet_name="Value Labels", header=None, dtype=object).iloc[2:, :3]
    vl.columns = ["variable", "value", "label"]
    vl["variable"] = vl["variable"].ffill()
    # Rows where col0 holds the value (continuation rows) have variable == value text: re-key them.
    cur, rows = None, []
    for var, val, lab in vl.itertuples(index=False):
        if pd.notna(lab) and pd.notna(val) and isinstance(var, str) and not re.fullmatch(r"-?\d+(\.0)?", str(var)):
            cur = var
        rows.append((cur, val, lab))
    labels = (pd.DataFrame(rows, columns=["variable", "value", "label"]).dropna(subset=["label"])
              .groupby("variable", sort=False)
              .apply(lambda g: "; ".join(f"{_fmt(a)}={b}" for a, b in zip(g["value"], g["label"], strict=False)),
                     include_groups=False))
    out = pd.DataFrame({
        "variable": v["Variable"].astype(str),
        "position": pd.to_numeric(v["Position"], errors="coerce").astype("Int64"),
        "label": v["Label"].fillna("").astype(str),
        "measurement_level": v["Measurement Level"].fillna("").astype(str),
    })
    out["value_labels"] = out["variable"].map(labels)
    return out.reset_index(drop=True)


def _fmt(v: object) -> str:
    try:
        f = float(v)
        return str(int(f)) if f.is_integer() else str(f)
    except (TypeError, ValueError):
        return str(v)


def read_microdata(file: Path | None = None) -> pd.DataFrame:
    """FinScope respondent-level CSV."""
    file = file or path("finscope_csv")
    try:
        return pd.read_csv(file, low_memory=False, encoding="utf-8")
    except UnicodeDecodeError:
        return pd.read_csv(file, low_memory=False, encoding="latin-1")


def topic_variables(dm: pd.DataFrame) -> dict[str, list[str]]:
    """Variables whose name or label matches each blueprint topic."""
    out = {}
    for topic, pat in TOPICS.items():
        rx = re.compile(pat, re.I)
        out[topic] = [v for v, lab in zip(dm["variable"], dm["label"], strict=False) if rx.search(v) or rx.search(lab)]
    return out


def profile_markdown(dm: pd.DataFrame, micro: pd.DataFrame) -> str:
    """FinScope profile report text (descriptive only)."""
    weights = [c for c in micro.columns if WEIGHT_PATTERN.search(c)]
    wlab = dict(zip(dm["variable"], dm["label"], strict=False))
    year_cols = [c for c in micro.columns if re.search(r"year|date|interview", c, re.I)]
    year_labels = dm[dm["label"].str.contains(r"\b20[0-2]\d\b", regex=True)]
    topics = topic_variables(dm)
    in_map = set(dm["variable"])
    in_csv = set(micro.columns)
    lines = [
        "# FinScope Tanzania microdata: profile",
        "",
        "Generated by `tzbank.ingest.finscope` (prompt 01 section 3.7). Descriptive profile only; no analysis.",
        "Evidence class: Observed (counts read from the data and data map).",
        "",
        "## Files",
        "",
        "- Microdata: `data/raw/finscope/FinScope.csv`",
        "- Data map: `data/raw/finscope/FinScope_Datamap.xlsx` (sheets: Variables, Value Labels)",
        "",
        "## Size",
        "",
        f"- Respondents (rows): {len(micro):,}",
        f"- Variables in microdata: {micro.shape[1]:,}",
        f"- Variables in data map: {len(dm):,}",
        f"- In data map but not in microdata: {', '.join(sorted(in_map - in_csv)) or 'none'}",
        f"- In microdata but not in data map: {', '.join(sorted(in_csv - in_map)) or 'none'}",
        "",
        "## Weights",
        "",
    ]
    if weights:
        for w in weights:
            s = pd.to_numeric(micro[w], errors="coerce")
            lines.append(f"- `{w}` ({wlab.get(w, 'no label')}): non-missing {s.notna().sum():,}; "
                         f"min {s.min():,.2f}; median {s.median():,.2f}; max {s.max():,.2f}; sum {s.sum():,.0f}")
        lines += ["", "`population_wt` is the person-level weight to use for adult-population estimates; "
                  "`Household_weight` is for household-level estimates. The sum of `population_wt` is the "
                  "weighted adult population the survey represents."]
    else:
        lines.append("- No weight variable found.")
    lines += ["", "## Survey year", ""]
    if year_cols or len(year_labels):
        lines.append(f"- Candidate date/year variables: {', '.join(year_cols) or 'none'}")
        for _, r in year_labels.iterrows():
            lines.append(f"- `{r['variable']}` label mentions a year: {r['label'][:120]}")
    lines += [
        "- **Not documented in the delivered files.** Neither the data map nor the microdata contains a survey-year,",
        "  interview-date or round variable, and no variable label states a year. The survey year must be confirmed",
        "  from the FinScope Tanzania survey report or FSDT metadata before any FinScope result is cited",
        "  (blueprint §6 data audit: 'survey year to confirm from documentation').",
        "- Indicators in the questionnaire (TIPS-era instruments such as Lipa Namba and AZAM Pay, cryptocurrency",
        "  questions) are consistent with the most recent FinScope Tanzania round (2023), but this is an inference",
        "  (evidence class: Interpretation), not documentation.",
        "",
        "## Variables relevant to the blueprint",
        "",
        "Matched on variable name or label; lists are for orientation, not a final selection.",
        "",
    ]
    for topic, vars_ in topics.items():
        lines.append(f"### {topic.replace('_', ' ').title()} ({len(vars_)} variables)")
        lines.append("")
        for v in vars_[:60]:
            lines.append(f"- `{v}`: {wlab.get(v, '')[:140]}")
        if len(vars_) > 60:
            lines.append(f"- ... and {len(vars_) - 60} more (see `data/interim/finscope_variables.csv`)")
        lines.append("")
    return "\n".join(lines)


def write_finscope(root: Path | None = None) -> list[Path]:
    """Write data/interim/finscope_variables.csv and reports/finscope_profile.md."""
    root = root or find_root()
    dm = read_datamap(path("finscope_datamap", root))
    if not path("finscope_csv", root).exists():
        # D15: the microdata is licensed by FSDT and not committed. Skip cleanly; keep the last profile.
        log.warning("FinScope microdata not found at %s; skipping the FinScope profile (D15). See README "
                    "'FinScope microdata' to obtain it.", path("finscope_csv", root))
        dm_out = dm.assign(blueprint_topics=None, in_microdata="unknown (microdata absent)", evidence_class="Observed")
        topics = topic_variables(dm)
        dm_out["blueprint_topics"] = dm_out["variable"].map(
            lambda v: ";".join(t for t, vs in topics.items() if v in vs) or None)
        return [write_csv(dm_out, path("interim", root) / "finscope_variables.csv")]
    micro = read_microdata(path("finscope_csv", root))
    dm_out = dm.copy()
    topics = topic_variables(dm)
    dm_out["blueprint_topics"] = dm_out["variable"].map(
        lambda v: ";".join(t for t, vs in topics.items() if v in vs) or None)
    dm_out["in_microdata"] = dm_out["variable"].isin(micro.columns).map({True: "Y", False: "N"})
    dm_out["evidence_class"] = "Observed"
    return [write_csv(dm_out, path("interim", root) / "finscope_variables.csv"),
            write_text(profile_markdown(dm, micro), path("reports", root) / "finscope_profile.md")]
