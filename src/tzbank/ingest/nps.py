"""BoT National Payment Systems panel ingest (prompt 01 section 3.6; blueprint §6, used in ch. 1, 2, 4.4 and 4.7).

Each panel sheet holds one or more tables: a title line, a 'Particulars' header row with years, data rows, and a
trailing notes column. Tables are reshaped to one long table. Cover and methodology sheets are kept as text.
"""

from __future__ import annotations

import re
from pathlib import Path

import openpyxl
import pandas as pd

from tzbank.config import find_root, path
from tzbank.io import write_csv, write_text

TEXT_SHEETS = {"Cover & Index", "Notes_Methodology"}
_UNIT = re.compile(r"\(([^)]*(?:TZS|USD|Million|Billion|million|billion|%|Number|No\.)[^)]*)\)")


def _cells(ws) -> list[list[object]]:
    return [list(r) for r in ws.iter_rows(values_only=True)]


def _nonempty(row: list[object]) -> list[object]:
    return [c for c in row if c is not None and str(c).strip() != ""]


def unit_from_label(label: str) -> str | None:
    """Unit stated in a 'Particulars' label, e.g. 'Value of transaction (TZS billion)' -> 'TZS billion'."""
    m = _UNIT.search(label)
    return m.group(1).strip() if m else None


def parse_sheet(ws) -> pd.DataFrame:
    """Reshape one NPS panel sheet into long rows."""
    rows = _cells(ws)
    sheet_title = str(_nonempty(rows[0])[0]) if rows and _nonempty(rows[0]) else ws.title
    source_note = str(_nonempty(rows[1])[0]) if len(rows) > 1 and _nonempty(rows[1]) else None
    out, table_title, years, notes_idx = [], sheet_title, None, None
    for r in rows[2:]:
        ne = _nonempty(r)
        if not ne:
            years = None
            continue
        first = r[0]
        if isinstance(first, str) and first.strip() == "Particulars":
            years, notes_idx = {}, None
            for j, h in enumerate(r[1:], start=1):
                hs = str(h).strip() if h is not None else ""
                if re.fullmatch(r"(19|20)\d\d", hs):
                    years[j] = int(hs)
                elif hs:
                    notes_idx = j
            continue
        if years is None:
            table_title = str(ne[0]).strip()
            continue
        particular = str(first).strip() if first is not None else ""
        if not particular:
            continue
        note = r[notes_idx] if notes_idx is not None and notes_idx < len(r) else None
        for j, yr in years.items():
            v = r[j] if j < len(r) else None
            if v is None or str(v).strip() == "":
                continue
            out.append({"sheet": ws.title, "table_title": table_title, "particular": particular, "year": yr,
                        "value": pd.to_numeric(v, errors="coerce"), "value_raw": str(v),
                        "unit": unit_from_label(particular), "source_note": source_note,
                        "row_note": None if note is None else str(note)})
    return pd.DataFrame(out)


def read_nps(file: Path | None = None) -> tuple[pd.DataFrame, dict[str, str]]:
    """Return (long table, {text sheet name: text})."""
    wb = openpyxl.load_workbook(file or path("nps"), read_only=True, data_only=True)
    parts, texts = [], {}
    for ws in wb.worksheets:
        if ws.title in TEXT_SHEETS:
            lines = [" | ".join(str(c) for c in _nonempty(r)) for r in _cells(ws)]
            texts[ws.title] = "\n".join(lines).strip()
            continue
        parts.append(parse_sheet(ws))
    wb.close()
    long = pd.concat(parts, ignore_index=True)
    long["evidence_class"] = "Observed"
    return long, texts


def write_nps(root: Path | None = None) -> list[Path]:
    """Write data/interim/nps_long.csv and docs/NPS_PANEL_NOTES.md."""
    root = root or find_root()
    long, texts = read_nps(path("nps", root))
    md = ["# BoT National Payment Systems panel: cover and methodology notes", "",
          "Generated by `tzbank.ingest.nps` from `data/raw/NPS_MultiYear_Panel_Dataset.xlsx` (text kept as delivered).",
          ""]
    for name, text in texts.items():
        md += [f"## {name}", "", "```text", text, "```", ""]
    return [write_csv(long, path("interim", root) / "nps_long.csv"),
            write_text("\n".join(md), path("docs", root) / "NPS_PANEL_NOTES.md")]


_RANGE = re.compile(r"(20\d\d)(?: report)? \((20\d\d)(?:/\d\d)?[–-](20\d\d)\)")
_REPORTS = re.compile(r"(20\d\d)\s*[–-]\s*(20\d\d)\s*(?:reports?|annexes)?")


def inferred_source_report(note: str, year: int) -> tuple[int | None, str]:
    """Latest NPS annual report whose annex covers ``year``, from the sheet's source note (prompt 02c, D31).

    The workbook keeps one value per series-year and no older vintages, so the source report is inferred, never
    read: explicit per-report ranges first; otherwise each report is taken to cover its own year and the four before
    it (the window the explicit ranges show).
    """
    note = str(note or "")
    ranges = [(int(r), int(a), int(b)) for r, a, b in _RANGE.findall(note)]
    if ranges:
        cover = [r for r, a, b in ranges if a <= year <= b]
        return (max(cover), "inferred: latest report whose stated range covers the year") if cover else (
            None, "year outside the stated report ranges")
    single = re.search(r"Source: (20\d\d) NPS Annual Report", note)
    if single:
        return int(single.group(1)), "stated: single report"
    m = _REPORTS.search(note)
    if m:
        first, last = int(m.group(1)), int(m.group(2))
        cover = [r for r in range(first, last + 1) if r - 4 <= year <= r]
        if cover:
            return max(cover), "inferred: latest report listed, assuming a five-year annex window"
    return None, "not inferable from the source note"


def canonical_name(series_id: str) -> str:
    """Crosswalk name of an NPS series: ``nps_`` + a slug of sheet, table and particular ('%' becomes 'pct')."""
    return "nps_" + re.sub(r"[^a-z0-9]+", "_", str(series_id).lower().replace("%", " pct ")).strip("_")


def nps_panel(long: pd.DataFrame) -> pd.DataFrame:
    """Processed NPS panel: one value per series-year as compiled by the owner, with the inferred source report."""
    p = long.copy()
    p["series_id"] = (p["sheet"] + "|" + p["table_title"].str.extract(r"^(Table [A-Z]\d+)")[0].fillna(p["table_title"])
                      + "|" + p["particular"]).str.replace(r"\s+", " ", regex=True)
    p.insert(0, "canonical_name", p["series_id"].map(canonical_name))
    p["annex_table"] = p["table_title"].str.extract(r"^(Table [A-Z]\d+)")[0]
    inf = [inferred_source_report(n, int(y)) for n, y in zip(p["source_note"], p["year"], strict=False)]
    p["source_report"] = [r for r, _ in inf]
    p["source_report_basis"] = [b for _, b in inf]
    p["doc_id"] = ("BOT-NPSAR-" + p["source_report"].astype("Int64").astype(str)).where(p["source_report"].notna())
    p["pdf_page"] = None  # the NPS workbook gives no page references
    p["vintage_note"] = "workbook holds one value per series-year (no older vintages to compare)"
    p["evidence_class"] = "Observed"
    return p


def write_nps_panel(root: Path | None = None) -> list[Path]:
    root = root or find_root()
    long = pd.read_csv(path("interim", root) / "nps_long.csv")
    from tzbank.ingest.adjudication import adjudicate
    from tzbank.pit.pubdates import attach_doc_dates

    pan = adjudicate(attach_doc_dates(nps_panel(long), root), "nps", root)
    from tzbank.extract.inclusion_nps_supplement import merge_supplements

    pan = merge_supplements(pan, "nps", root)  # D39: code-extracted, below the owner's values
    return [write_csv(pan, path("processed", root) / "nps_panel.csv", require_evidence=True)]
