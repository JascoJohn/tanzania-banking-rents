"""All registered hypotheses with their verdicts, one table (prompt 16 follow-up; findings pack v1.8).

``outputs/tables/hypotheses_all.csv``: one row per hypothesis registered in ``docs/RESEARCH_HYPOTHESES.md`` (blueprint
§0 hypothesis register), with columns hypothesis, statement (as registered), verdict (worded exactly as in the
chapter's ``chNN_hypotheses`` table; chapter 4 from ``hypotheses_status.csv``, which carries H4.1-H4.2), chapter, the
source table and the evidence class (Interpretation). Revisits recorded in a later chapter (``H5.3 (revisited)`` in
chapter 6) stay in that chapter's table; this table keeps the registered hypothesis's own verdict. A registered
hypothesis without a verdict fails the stage (no silent gap). Written by the findings stage with its manifest
(``outputs/manifests/hypotheses.json``, shown on the dashboard landing page) so the findings pack carries it.
"""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

from tzbank.config import find_root, path
from tzbank.io import write_csv, write_json, write_text

HYP = re.compile(r"^- (H(\d+)\.\d+)\s+(.+)$")


NOTE = """# All registered hypotheses and verdicts

Generated by `tzbank.reporting.hypotheses_all` (stage `findings`).

## Research question
Blueprint §0 and chapters 1-12: what each registered hypothesis states and the verdict its chapter reached.

## Variable definitions
`hypothesis` (register id), `statement` (as worded in `docs/RESEARCH_HYPOTHESES.md`), `verdict` (as worded in the
chapter table), `chapter`, `source_table` (`docs/VARIABLE_DICTIONARY.md`).

## Sources
`docs/RESEARCH_HYPOTHESES.md`; `outputs/tables/chNN_hypotheses.csv`; `outputs/tables/hypotheses_status.csv` (H4.1-H4.2,
chapter 4 has no table of its own). Function: `tzbank.reporting.hypotheses_all.build`.

## Validation test
`tests/test_build_reports.py::test_hypotheses_all`: one row per registered hypothesis, verdict wording taken from the
chapter's own table.

## Result
{n} hypotheses registered, every one with a verdict ({counts}).

## Evidence class
Interpretation. The table is a register, not new evidence: a verdict's grounds, rule and caveats are in its chapter's
table and note. It lets the reports cite every verdict from one pipeline table.

## Limitations
A revisit recorded in a later chapter (H5.3 revisited in chapter 6) stays in that chapter's table; this table keeps
the registered hypothesis's own verdict. A registered hypothesis without a verdict stops the stage.
"""


def register(root: Path) -> pd.DataFrame:
    """Hypotheses as registered: id, statement, chapter (docs/RESEARCH_HYPOTHESES.md)."""
    rows = []
    for ln in (root / "docs" / "RESEARCH_HYPOTHESES.md").read_text(encoding="utf-8").splitlines():
        m = HYP.match(ln.strip())
        if m:
            rows.append({"hypothesis": m.group(1), "statement": m.group(3).strip(), "chapter": int(m.group(2))})
    if not rows:
        raise ValueError("no hypotheses found in docs/RESEARCH_HYPOTHESES.md")
    return pd.DataFrame(rows).drop_duplicates("hypothesis")


def verdicts(root: Path) -> pd.DataFrame:
    """hypothesis -> verdict and source table, from every chNN_hypotheses table (and hypotheses_status for H4)."""
    tab = path("tables", root)
    out = []
    for f in sorted(tab.glob("ch[0-9][0-9]_hypotheses.csv")):
        d = pd.read_csv(f)
        out += [{"hypothesis": h, "verdict": v, "source_table": f.name} for h, v in zip(d["hypothesis"], d["verdict"],
                                                                                         strict=True)]
    s = tab / "hypotheses_status.csv"
    if s.exists():
        d = pd.read_csv(s)
        out += [{"hypothesis": h, "verdict": v, "source_table": s.name} for h, v in zip(d["hypothesis"], d["verdict"],
                                                                                         strict=True)]
    v = pd.DataFrame(out)
    return v.drop_duplicates("hypothesis", keep="first")  # the chapter's own table comes first


def build(root: Path | None = None) -> pd.DataFrame:
    root = root or find_root()
    reg = register(root)
    t = reg.merge(verdicts(root), on="hypothesis", how="left")
    missing = t[t["verdict"].isna()]["hypothesis"].tolist()
    if missing:
        raise ValueError(f"registered hypotheses without a verdict in any chNN_hypotheses table: {', '.join(missing)}")
    return t[["hypothesis", "statement", "verdict", "chapter", "source_table"]].assign(evidence_class="Interpretation")


def write(root: Path | None = None) -> list[Path]:
    root = root or find_root()
    t = build(root)
    f = write_csv(t, path("tables", root) / "hypotheses_all.csv", require_evidence=True)
    counts = t["verdict"].value_counts().to_dict()
    note = write_text(NOTE.format(n=len(t), counts="; ".join(f"{k}: {v}" for k, v in counts.items())),
                      path("notes", root) / "hypotheses.md")
    m = {"chapter": "hypotheses", "title": "All registered hypotheses and verdicts", "status": "complete",
         "hypotheses": t["hypothesis"].tolist(),
         "tables": [{"path": f.relative_to(root).as_posix(), "evidence_class": "Interpretation",
                     "note": note.relative_to(root).as_posix(),
                     "description": "Every registered hypothesis (docs/RESEARCH_HYPOTHESES.md) with its verdict as "
                                    "worded in the chapter tables"}],
         "figures": [], "notes": [note.relative_to(root).as_posix()],
         "inputs": ["docs/RESEARCH_HYPOTHESES.md", "outputs/tables/ch*_hypotheses.csv",
                    "outputs/tables/hypotheses_status.csv"],
         "module": "tzbank.reporting.hypotheses_all", "run_log_stage": "findings"}
    return [f, note, write_json(m, path("manifests", root) / "hypotheses.json")]
