"""Draft check (prompt 13 item 15): ``python -m tzbank.reporting.draft_check`` writes ``outputs/findings/fill_list.md``.

For every owner draft in ``drafts/*.docx`` (never edited): (1) each ``[refresh: pack]``, ``[to rerun ...]`` and
``[export]`` marker with its sentence and the findings-pack ids that fill it (a topic map from the sentence to id
prefixes; a draft named for one bank is filtered to that bank); (2) each number the figure checker finds mismatched,
with the nearest pack value and id ("verify": the nearest value is a suggestion, not a confirmed match).
"""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

from tzbank.config import find_root, path
from tzbank.reporting.check_figures import check, read_text

MARKER = re.compile(r"\[(refresh[^\]]*|to rerun[^\]]*|export[^\]]*)\]", re.I)
TOPICS: list[tuple[str, list[str]]] = [
    (r"implied (long-run )?(excess return|ROE|cost of equity)|prices imply|price implies|market prices a",
     ["CH10.IMPLIED.IMPLIED_ER_STAR_AT_CH5_LAMBDA", "CH10.IMPLIED.IMPLIED_ROE_STAR", "CH10.IMPLIED.IMPLIED_COE"]),
    (r"rerating|log-point|log point|residual", ["CH10.RERATING", "CH10.BRIDGE"]),
    (r"justified P/B", ["CH09.VALUATIONS.JUSTIFIED_PB", "CH09.VALUATIONS.MARKET_PB"]),
    (r"scenario path|bear EPS|year three|year one'?s base ROE|ROE \d+ and \d+ points",
     ["CH11.SCENARIOS", "CH13.ROE_RECONCILE"]),
    (r"Monte Carlo|outcomes above the price|centring|re-centring|Re-centring|Value above price",
     ["CH11.MONTE_CARLO.PROB_VALUE_ABOVE_PRICE", "CH11.MONTE_CARLO.P50"]),
    (r"year-one base ROE|year one'?s base ROE|unreconciled|not yet reconciled", ["CH13.ROE_RECONCILE"]),
    (r"break-even|breakeven", ["CH13.FRANCHISE_BREAKEVEN", "CH13.USD_EXPORTS.VALUE"]),
    (r"one-point fall|bill rate costs|ROE points", ["CH13.RATE_SENSITIVITY"]),
    (r"agricultur|implied shares|from amounts", ["CH13.IMPLIED_CREDIT_SHARES"]),
    (r"rating flip|single parameter", ["CH13.RATING_FLIPS"]),
    (r"2015.18|stress can recur|weight placed", ["CH13.STRESS_MIXTURE", "CH11.MONTE_CARLO"]),
    (r"rate-consistent", ["CH13.RATE_CONSISTENT"]),
    (r"dominance without excess return|named scenario", ["CH13.NAMED_SCENARIOS"]),
    (r"pre-rally|rally", ["CH13.CAPACITY_WINDOWS"]),
    (r"block against board|block", ["CH13.BLOCK_BOARD"]),
    (r"direct 2025 profit share|compression", ["CH13.CR2_PROFIT_DIRECT"]),
    (r"surplus|tenth of profit", ["CH13.SURPLUS_DRAG"]),
    (r"price series|52-week", ["CH13.PRICE_LINES", "CH13.PRICE_SERIES"]),
    (r"2018 closures|Bank M|event test", ["CH13.EVENT_2018"]),
    (r"entry price", ["CH13.USD_EXPORTS.VALUE"]),
    (r"joint|currency and credit stress", ["CH13.USD_EXPORTS.VALUE"]),
    (r"depreciation", ["CH13.USD_EXPORTS.VALUE", "CH12.EXPECTED_USD"]),
    (r"approach B", ["CH09.COE_AB"]),
    (r"global bank|own history|top of its range|three times", ["CH13.VALUATION_BANDS", "CH13.KPI_TABLE",
                                                                "CH13.BENCHMARKS"]),
    (r"payout", ["CH11.SCENARIOS", "CH13.FINANCIAL_TABLE"]),
    (r"African banks|peer|KCB|Equity", ["CH13.PEERS", "CH13.KPI_TABLE"]),
    (r"cost of equity", ["CH09.COE_AB", "CH10.IMPLIED.IMPLIED_COE"]),
]


def _sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"(?<=[.!?\]])\s+|\n", text) if s.strip()]


def _ids(pack: pd.DataFrame, sentence: str, bank: str | None, marker: str) -> list[str]:
    pref = []
    if marker.lower().startswith("export"):
        pref = ["CH13.FINANCIAL_TABLE"]
    for pat, ids in TOPICS:
        if re.search(pat, sentence + " " + marker, re.I):
            pref += [i for i in ids if i not in pref]
    if not pref:
        return []
    hit = pack[pack["id"].str.startswith(tuple(pref))]
    if bank:
        hit = hit[hit["bank"].fillna("").isin(["", bank]) | hit["id"].str.contains(f".{bank}.", regex=False)]
    return [f"`{r.id}` = {_fmt(r)}" for r in hit.head(8).itertuples()] + (
        [f"... {len(hit) - 8} more under {', '.join(f'`{p}`' for p in pref)}"] if len(hit) > 8 else [])


def _fmt(r) -> str:
    try:
        v = float(r.value)
    except (TypeError, ValueError):
        return str(r.value)
    return f"{v:.1%}" if r.unit == "ratio" else f"{v:,.4g}" if abs(v) < 100 else f"{v:,.0f}"


def fill_list(root: Path | None = None) -> str:
    root = root or find_root()
    from tzbank.reporting.findings import latest_pack

    pack_f = latest_pack(root)
    pack = pd.read_csv(pack_f, low_memory=False)
    out = ["# Fill list for the owner's drafts", "",
           f"Generated by `tzbank.reporting.draft_check` against `{pack_f.relative_to(root).as_posix()}` (register "
           f"{pack['register_version'].iloc[0]}). The drafts in `drafts/` are not edited. Pack ids are suggestions from "
           "the sentence's topic: confirm each before filling. Mismatches show the nearest pack value (verify).", ""]
    for f in sorted((root / "drafts").glob("*.docx")):
        bank = "NMB" if f.name.startswith("NMB") else "CRDB" if f.name.startswith("CRDB") else None
        text = read_text(f)
        sents = _sentences(text)
        marks = [(s, m.group(1)) for s in sents for m in MARKER.finditer(s)]
        res = check(f, pack_f, root)
        mm = res[res["status"] == "mismatch"]
        um = res[res["status"] == "unmatched"]
        c = res["status"].value_counts()
        out += [f"## {f.name}", "",
                f"Markers: {len(marks)} ([refresh: pack] {sum(m.lower().startswith('refresh') for _, m in marks)}, "
                f"[to rerun] {sum(m.lower().startswith('to rerun') for _, m in marks)}, [export] "
                f"{sum(m.lower().startswith('export') for _, m in marks)}). Figures: "
                f"{int(c.get('matched', 0))} matched, {len(mm)} mismatched, {len(um)} not in the pack, "
                f"{int(c.get('ignored', 0))} ignored, {int(c.get('external', 0))} external (not matched).", "",
                "### Markers", ""]
        seen = set()
        n_export = 0
        for s, m in marks:
            if m.lower().startswith("export") and s.strip() == "[export]":
                n_export += 1
                continue
            key = (s[:80], m)
            if key in seen:
                continue
            seen.add(key)
            ids = _ids(pack, s, bank, m)
            out.append(f"- **[{m}]** {s[:300]}")
            out += [f"  - {i}" for i in ids] if ids else ["  - no pack id mapped: owner to place (or a collection "
                                                          "task)"]
        if n_export:
            out.append(f"- **[export] x {n_export}** (table cells): fill from `outputs/tables/ch13_financial_table.csv` "
                       f"(pack ids `CH13.FINANCIAL_TABLE.<column>.{bank or '<bank>'}.FY<year><A|E>`)")
        out += ["", "### Mismatched figures (nearest pack value; verify)", ""]
        out += [f"- line {r.line}: **{r.text}** -> {r.pack_ids} | {r.context[:160]}" for r in mm.itertuples()] or [
            "- none"]
        out += ["", "### Figures not in the pack", ""]
        out += [f"- line {r.line}: **{r.text}** | {r.context[:160]}" for r in um.itertuples()] or ["- none"]
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    import sys

    root = find_root()
    txt = fill_list(root)
    f = path("outputs", root) / "findings" / "fill_list.md"
    f.write_text(txt, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(f"written {f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
