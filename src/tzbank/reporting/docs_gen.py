def write_docs(root: Path | None = None) -> list[Path]:
    """Write generated docs; seed hand-maintained docs only when absent."""
    root = root or find_root()
    d = path("docs", root)
    out = [write_text(variable_dictionary(root), d / "VARIABLE_DICTIONARY.md"),
           write_text(source_register(root), d / "SOURCE_REGISTER.md")]
    if not bp.is_full(root):  # public repository (prompt 26, D97): the blueprint-derived docs ship as published
        log.info("docs: research blueprint not present; RESEARCH_HYPOTHESES, DATA_REQUIREMENTS and RESEARCH_FRAME "
                 "are kept as published")
        return out
    out += [write_text(research_hypotheses(root), d / "RESEARCH_HYPOTHESES.md"),
            write_text(data_requirements(root), d / "DATA_REQUIREMENTS.md"),
            write_text(bp.frame(root), d / bp.FRAME)]
    for name, fn in [("EMPIRICAL_METHODOLOGY.md", empirical_methodology),
                     ("EVIDENCE_AND_LIMITATIONS.md", evidence_and_limitations), ("DECISION_LOG.md", decision_log)]:
        if not (d / name).exists():
            out.append(write_text(fn(root), d / name))
    return out
