def source_register(root: Path) -> str:
    """docs/SOURCE_REGISTER.md from the Sources table and data/raw/MANIFEST.csv."""
    src = pd.read_csv(path("processed", root) / "sources.csv")
    man = pd.read_csv(path("manifest", root), dtype=str)
    docs = man[man["file"].str.startswith("documents/")]
    files = man[~man["file"].str.startswith("documents/")]
    cols = [c for c in ["Doc ID", "Owner", "Document Type", "Period Covered", "publication_date",
                        "publication_date_type", "rule_applied", "regulatory_basis", "FS Board Approval Date",
                        "Auditor Report Date", "Legacy Publication Date (pre-D16)", "Primary / Secondary", "URL"]
            if c in src.columns]
    s = src[cols].copy()
    if "URL" in s.columns:
        s["URL"] = s["URL"].fillna("").map(lambda u: u if str(u).startswith("http") else "(local path)" if u else "")
    by_folder = (docs.assign(folder=docs["file"].str.split("/").str[1])
                 .groupby("folder").agg(files=("file", "size"), bytes=("bytes", lambda b: f"{sum(map(int, b)):,}"))
                 .reset_index())
    return "\n".join([
        "# Source register", "", GEN.format(src="the inputs workbook Sources sheet and data/raw/MANIFEST.csv"), "",
        "Source PDFs are not committed (third-party copyright, CLAUDE.md 9); each is listed in MANIFEST.csv with its "
        "sha256. Publication dates follow D16 (`docs/PUBLICATION_DATE_RULES.md`): actual where evidence exists, "
        "otherwise the regulatory estimate; approval and auditor dates are shown separately.", "",
        f"## Documents registered in the inputs workbook ({len(s)})", "", _md(s), "",
        f"## Raw data files ({len(files)})", "",
        _md(files[["file", "sha256", "bytes", "received_date", "description", "committed (Y/N)"]]), "",
        f"## Source documents held locally ({len(docs)} files, git-ignored)", "", _md(by_folder), "",
        "Per-file hashes: `data/raw/MANIFEST.csv`.", ""])


