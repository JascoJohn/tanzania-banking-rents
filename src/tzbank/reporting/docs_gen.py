def research_hypotheses(root: Path) -> str:
    """docs/RESEARCH_HYPOTHESES.md from blueprint sections 3-5."""
    hyp = bp.hypotheses(root)
    chs = {c["number"]: c for c in bp.chapters(root)}
    lines = ["# Research hypotheses", "", GEN.format(src="docs/RESEARCH_BLUEPRINT.md sections 1 and 3-5"), "",
             "Every hypothesis is stated so the data can reject it (blueprint section 3).", ""]
    part = None
    for n in sorted(hyp):
        c, h = chs[n], hyp[n]
        if c["part"] != part:
            part = c["part"]
            lines += [f"## Part {part}", ""]
        lines += [f"### Chapter {n}. {c['title']}", "", f"**Central question.** {c['question']}", "",
                  f"**Primary output.** {c['output']}", "", "**Hypotheses**", ""]
