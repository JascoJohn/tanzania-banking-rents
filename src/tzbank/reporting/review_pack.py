"""Review pack (prompt 02b section 4): one folder the owner uploads for review before chapter 4.

Regenerated by ``run all`` (last stage) into reports/review_pack/ (git-tracked). Files that come from the extraction
tooling (pdf_inspection.csv, manual_check_list.csv) are copied as they stand; a missing file is listed in the index.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pandas as pd

from tzbank.config import find_root, path
from tzbank.io import write_text

PACK = [
    "reports/validation/validation_report.md",
    "reports/data_audit.md",
    "reports/manual_check_list.csv",
    "docs/DEFINITIONS.md",
    "docs/PUBLICATION_DATE_RULES.md",
    "data/processed/coe_inputs_annual.csv",
    "data/processed/bank_year_wide.csv",
    "outputs/tables/ch04_dupont_panel.csv",
    "reports/collection_tasks.csv",
    "data/processed/coe_long_bond_comparison.csv",
    "reports/validation/outliers.csv",
    "reports/validation/plausibility_flags.csv",
    "reports/validation/deposit_interest_reconciliation.csv",
    "reports/inclusion_nps_adjudication.csv",
]


def _table(df: pd.DataFrame) -> str:
    from tzbank.validate.run import _md_table

    return _md_table(df)


def inspection_summary(root: Path) -> str:
    """pdf_inspection_summary.md: counts by outcome, bank and variable."""
    f = path("reports", root) / "pdf_inspection.csv"
    if not f.exists():
        return "# PDF inspection summary\n\n`reports/pdf_inspection.csv` not found.\n"
    d = pd.read_csv(f)
    d["outcome"] = d["extractable"].map({"Y": "extracted", "partial": "located, failed gate (manual)",
                                         "N": "not extracted"})
    d.loc[d["extractable"] == "N", "outcome"] = d.loc[d["extractable"] == "N", "reason_if_not"]
    docs = pd.read_csv(path("reports", root) / "pdf_documents.csv") if (path("reports", root) / "pdf_documents.csv"
                                                                        ).exists() else pd.DataFrame()
    lines = ["# PDF inspection summary", "",
             "Generated by `tzbank.reporting.review_pack` from `reports/pdf_inspection.csv` (one row per open gap: "
             "bank x variable x year; prompt 02 section 1.1 and prompt 02b).", "",
             f"Gaps inspected: {len(d)}.", "", "## By outcome", "",
             _table(d["outcome"].value_counts().rename_axis("outcome").reset_index(name="gaps")), "",
             "## By bank and outcome", "",
             _table(pd.crosstab(d["bank_id"], d["outcome"]).reset_index()), "",
             "## By variable and outcome", "",
             _table(pd.crosstab(d["variable"], d["outcome"]).reset_index()), ""]
    if len(docs):
        lines += ["## Documents by text layer and OCR status", "",
                  _table(docs.groupby(["text_layer", "ocr_status"]).size().reset_index(name="pdfs")), ""]
    return "\n".join(lines)


def write_review_pack(root: Path | None = None) -> list[Path]:
    root = root or find_root()
    out = path("reports", root) / "review_pack"
    out.mkdir(parents=True, exist_ok=True)
    files, missing = [], []
    for rel in PACK:
        src = root / rel
        if src.exists():
            dst = out / src.name
            shutil.copyfile(src, dst)
            files.append(dst)
        else:
            missing.append(rel)
    files.append(write_text(inspection_summary(root), out / "pdf_inspection_summary.md"))
    idx = ["# Review pack (prompt 02b)", "", "Regenerated by `python -m tzbank run all`. Contents:", ""]
    idx += [f"- `{f.name}`" for f in files] + [""]
    if missing:
        idx += ["Missing at generation time:", ""] + [f"- `{m}`" for m in missing] + [""]
    files.append(write_text("\n".join(idx), out / "README.md"))
    return files
