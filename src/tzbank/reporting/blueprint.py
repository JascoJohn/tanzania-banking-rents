"""Read docs/RESEARCH_BLUEPRINT.md (the master document) into structured text: sections, chapter table,
hypotheses and chapter 4 subsections. Text parsing only; no numbers are computed here.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

from tzbank.config import find_root, path

FRAME = "RESEARCH_FRAME.md"  # the public extract (prompt 26, D97)


def full_file(root: Path | None = None) -> Path:
    """Path to docs/RESEARCH_BLUEPRINT.md (the master document; not in the public repository)."""
    return path("docs", root or find_root()) / "RESEARCH_BLUEPRINT.md"


def is_full(root: Path | None = None) -> bool:
    """True when the full blueprint is present (the private repository)."""
    return full_file(root).exists()


def blueprint_file(root: Path | None = None) -> Path:
    """The full blueprint when present, else docs/RESEARCH_FRAME.md: the extract of the sections the dashboard and
    the generated docs read (central proposition, chapter questions, hypotheses, limitations; prompt 26, D97)."""
    return full_file(root) if is_full(root) else path("docs", root or find_root()) / FRAME


def frame(root: Path | None = None) -> str:
    """docs/RESEARCH_FRAME.md from the full blueprint, in the blueprint's own format so the same parsers read it:
    section 0's central proposition, section 1's chapter table, the hypothesis and subsection tables of sections 3-5
    and the limitations table of section 7. Text only."""
    sec = sections(root)
    out = ["# Research frame: The Economics of Dominance and Rents", "",
           "Generated by `python -m tzbank run audit` from the research blueprint: the chapter questions, hypotheses "
           "and limitations the dashboard shows. Hypotheses were set before the analysis was run.", ""]
    out += [sec["0"].splitlines()[0], "", f"**Central proposition.** {central_proposition(root)}", ""]
    for num in ("1", "3", "4", "5", "7"):
        out += [sec[num].splitlines()[0], ""]
        for line in _table_blocks(sec[num], ("Part", "Chapter", "Hypotheses", "Subsection", "Limitation")):
            out.append(line)
        out.append("")
    return "\n".join(out)


def _table_blocks(block: str, heads: tuple[str, ...]) -> list[str]:
    """Raw markdown lines of the tables in a block whose first header cell starts with one of ``heads`` (or whose
    header contains 'Hypotheses' or 'Limitation')."""
    out, cur = [], []
    for line in block.splitlines() + [""]:
        if line.strip().startswith("|"):
            cur.append(line)
            continue
        if cur:
            head = cur[0]
            first = head.strip().strip("|").split("|")[0].strip()
            if first.startswith(heads) or "Hypotheses" in head or "Limitation" in head:
                out += cur + [""]
            cur = []
    return out


@lru_cache(maxsize=2)
def _text(file: str) -> str:
    return Path(file).read_text(encoding="utf-8")


def text(root: Path | None = None) -> str:
    """Full blueprint text."""
    return _text(str(blueprint_file(root)))


def sections(root: Path | None = None) -> dict[str, str]:
    """'## N. Title' sections keyed by number string ('0'..'8'), body including the heading."""
    out: dict[str, str] = {}
    parts = re.split(r"(?m)^(?=## \d+\.)", text(root))
    for p in parts:
        m = re.match(r"## (\d+)\.", p)
        if m:
            out[m.group(1)] = p.strip()
    return out


def section_title(num: str, root: Path | None = None) -> str:
    """Heading text of a section."""
    return sections(root)[num].splitlines()[0].lstrip("# ").strip()


def tables(block: str) -> list[list[dict[str, str]]]:
    """All markdown tables in a block as lists of row dicts."""
    out, cur, header = [], [], None
    for line in block.splitlines() + [""]:
        if line.strip().startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if header is None:
                header = cells
            elif all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                continue
            else:
                cur.append(dict(zip(header, cells, strict=False)))
        else:
            if header is not None:
                out.append(cur)
            cur, header = [], None
    return out


def chapters(root: Path | None = None) -> list[dict[str, str]]:
    """Chapter table of section 1: number, title, part, question, output."""
    rows, part = [], ""
    for r in tables(sections(root)["1"])[0]:
        part = r.get("Part") or part
        m = re.match(r"(\d+)\.\s*(.+)", r.get("Chapter", ""))
        if not m:
            continue
        rows.append({"number": int(m.group(1)), "title": m.group(2).strip(), "part": part,
                     "question": r.get("Central empirical question", ""), "output": r.get("Primary output", "")})
    return rows


def hypotheses(root: Path | None = None) -> dict[int, dict[str, object]]:
    """Per chapter: hypotheses list, test, data held/needed, achievable strength (sections 3-5)."""
    out: dict[int, dict[str, object]] = {}
    for sec in ["3", "4", "5"]:
        for tab in tables(sections(root)[sec]):
            if not tab or "Hypotheses" not in tab[0]:
                continue
            for r in tab:
                m = re.match(r"(\d+)\.", r["Chapter"])
                if not m:
                    continue
                hs = [h.strip() for h in re.split(r"(?=\bH\d+\.\d+\s)", r["Hypotheses"]) if h.strip()]
                out[int(m.group(1))] = {"chapter": r["Chapter"], "hypotheses": hs, "test": r.get("Test", ""),
                                        "data": r.get("Data held / needed", ""),
                                        "strength": r.get("Achievable strength", ""), "section": sec}
    return out


def ch4_subsections(root: Path | None = None) -> list[dict[str, str]]:
    """Chapter 4 subsections 4.0-4.7 (section 4)."""
    for tab in tables(sections(root)["4"]):
        if tab and "Subsection" in tab[0]:
            rows = []
            for r in tab:
                m = re.match(r"(4\.\d)\s+(.+)", r["Subsection"])
                if m:
                    rows.append({"number": m.group(1), "title": m.group(2), "investigation": r["Investigation"],
                                 "measures": r["Core measures"]})
            return rows
    return []


def central_proposition(root: Path | None = None) -> str:
    """The 'Central proposition' paragraph of section 0."""
    m = re.search(r"\*\*Central proposition\.\*\*\s*(.+)", sections(root)["0"])
    return m.group(1).strip() if m else ""


def decision_log(root: Path | None = None) -> list[dict[str, str]]:
    """Decision log rows (section 8)."""
    for tab in tables(sections(root)["8"]):
        if tab and "Decision" in tab[0]:
            return tab
    return []
