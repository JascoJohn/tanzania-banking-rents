def write_transactions(root: Path | None = None) -> list[Path]:
    root = root or find_root()
    t = tickers(root)
    b = bank_metrics(wide(root))
    m = market_context(root)
    tab, figd = path("tables", root), path("figures", root)
    files = [write_csv(b, tab / "ch04_4_4_transactions.csv", require_evidence=True),
             write_csv(m, tab / "ch04_4_4_market_context.csv", require_evidence=True)]
    fig, ax = plt_subplots(figsize=(8, 4.4))
    for bk in FOCUS:
        d = b[b["bank_id"] == bk]
        ax.plot(d["fiscal_year"], d["fee_to_avg_assets"] * 100, color=COLORS[bk], lw=2, marker="o", ms=3,
                label=f"{t[bk]} fees / avg assets")
        ax.plot(d["fiscal_year"], d["fx_to_avg_assets"] * 100, color=COLORS[bk], lw=1, ls="--",
                label=f"{t[bk]} FX / avg assets")
    style(ax, "Fee and FX income relative to average assets, NMB and CRDB", "percent")
    ax.legend(ncol=2, fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.12))
    png = save(fig, figd / "ch04_4_4_fees_fx.png", "Evidence class: Derived. Gross fee income (note total) and net FX "
               "income over average total assets.")
    data = write_csv(b[b["bank_id"].isin(FOCUS)][["bank_id", "fiscal_year", "fee_to_avg_assets", "fx_to_avg_assets",
                                                  "evidence_class"]], figd / "ch04_4_4_fees_fx_data.csv",
                     require_evidence=True)
    figs = [{"path": png, "data": data, "description": "Fee and FX income per unit of assets",
             "evidence_class": "Derived"}]
    files += [png, data]
    lines = []
    for bk in FOCUS:
        d = b[(b["bank_id"] == bk)].dropna(subset=["fee_to_avg_assets"])
        if len(d):
            r = d.iloc[-1]
            lines.append(f"- {t[bk]} FY{int(r['fiscal_year'])}: fees {pct(r['fee_to_avg_assets'], 2)} of average "
                         f"assets; digital channels {pct(r['digital_share_of_fees'], 1, reason='fee type not split')} "
                         f"and cards {pct(r['cards_share_of_fees'], 1, reason='fee type not split')} of fees (LOW confidence: label-"
                         "matched fee types); FX "
                         f"{pct(r['fx_to_avg_assets'], 2, reason='FX line not extracted')} of average assets.")
        p = b[(b["bank_id"] == bk)].dropna(subset=["fee_per_customer"])
        if len(p):
            r = p.iloc[-1]
            lines.append(f"  Fee per customer FY{int(r['fiscal_year'])}: TZS {num(r['fee_per_customer'])} (band "
                         f"{num(r['fee_per_customer_low'])}-{num(r['fee_per_customer_high'])}; MEDIUM).")
    mm = m[m["series"].str.startswith("Mobile money transactions")].sort_values("year")
    if len(mm) >= 2:
        g = (mm["value"].iloc[-1] / mm["value"].iloc[0]) ** (1 / (mm["year"].iloc[-1] - mm["year"].iloc[0])) - 1
        lines.append(f"- Market-level: mobile money transaction value grew {pct(g, 1)} a year "
                     f"{int(mm['year'].iloc[0])}-{int(mm['year'].iloc[-1])} (NPS, all providers).")
    interp = ("**Interpretation.** Transaction income is a secondary engine for both banks "
              "(4.0 ranks non-interest income behind leverage and asset yield in the gap). Fast market-level growth "
              "of mobile money is a disruption risk to bank transaction fees and to cheap transactional deposits.")
    nf = note(root, "4.4", NOTE.format(band=KPI_BAND, results="\n".join(lines), interpretation=interp))
    tables = [{"path": files[0], "description": "Fee and FX income: per asset, per customer and per agent (bands)",
               "evidence_class": "Derived"},
              {"path": files[1], "description": "Payments market context (NPS, H12): market-level, not bank-level",
               "evidence_class": "Observed"}]
    files += [nf, manifest(root, "4.4", "Transaction economics", tables, figs, nf, "tzbank.chapters.ch04.transactions",
                           ["data/processed/bank_year_wide.csv", "data/processed/nps_panel.csv"],
                           "built - KPI ratios MEDIUM confidence")]
    return files
