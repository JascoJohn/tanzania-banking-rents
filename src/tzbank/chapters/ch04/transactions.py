"""Chapter 4.4: transaction economics (blueprint §4, 4.4; H4.2).

Fee income by type, per customer, per agent and per average asset; net FX income; and the payments market around
the banks from the NPS panel and Table H12 (digital savings and credit), always labelled **market-level**, never
bank-level. KPIs (customers, agents) are MEDIUM confidence (prompt 03a), so per-KPI ratios carry a +/-10% band.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from tzbank.chapters.ch04.common import COLORS, FOCUS, avg, col, div, manifest, note, num, pct, plt_subplots, save, style, tickers, wide
from tzbank.config import find_root, path
from tzbank.io import write_csv

KPI_BAND = 0.10  # MEDIUM-confidence KPIs: ratios shown with a +/-10% band (prompt 03b quality gate)
MARKET = {  # NPS panel series used as market context (owner panel, D30)
    "nps_08_mobilemoney_table_h1_value_tzs_billion": "Mobile money transactions, value (TZS bn)",
    "nps_08_mobilemoney_table_h1_mobile_money_users_active": "Mobile money active users",
    "nps_08_mobilemoney_table_h1_number_of_agents": "Mobile money agents",
    "nps_12_mobilebanking_panel_mobile_banking_annex_l_active_users": "Mobile banking active users (all banks)",
    "nps_10_internetbanking_panel_internet_banking_annex_j_number_of_active_customers":
        "Internet banking active customers (all banks)",
    "nps_05_cards_panel_card_records_annex_e_total_value_of_card_transactions_tzs_billion":
        "Card transactions, value (TZS bn)",
}
H12 = ("code_nps_table_h12_digital_savings_value_of_transactions_tzs_billions_",
       "code_nps_table_h12_digital_credit_value_of_transactions_tzs_billions_")


def bank_metrics(w: pd.DataFrame) -> pd.DataFrame:
    fee = col(w, "fee_income_total")
    out = pd.DataFrame({"bank_id": w["bank_id"], "fiscal_year": w["fiscal_year"], "fee_income": fee,
                        "fx_income": col(w, "fx_income")})
    out["fee_to_avg_assets"] = div(fee, avg(w, "total_assets"))
    out["fx_to_avg_assets"] = div(col(w, "fx_income"), avg(w, "total_assets"))
    out["fee_share_of_nonii"] = div(fee, col(w, "non_interest_income"))
    out["digital_share_of_fees"] = div(col(w, "fee_income_digital"), fee)
    out["cards_share_of_fees"] = div(col(w, "fee_income_cards"), fee)
    # 03b review fix 3: fee types are matched from printed labels; LOW until the mapping is verified
    out["fee_type_share_confidence"] = "LOW (label-matched fee types; excluded from 4.7 verdicts)"
    for k, c in [("customer", "kpi_customers"), ("agent", "kpi_agents")]:
        v = div(fee, col(w, c))
        out[f"fee_per_{k}"] = v
        out[f"fee_per_{k}_low"], out[f"fee_per_{k}_high"] = v / (1 + KPI_BAND), v / (1 - KPI_BAND)
        out[f"fee_per_{k}_confidence"] = "MEDIUM (KPI from narrative pages)"
    out["evidence_class"] = "Derived"
    return out[out[["fee_income", "fx_income"]].notna().any(axis=1)].reset_index(drop=True)


def market_context(root: Path) -> pd.DataFrame:
    n = pd.read_csv(path("processed", root) / "nps_panel.csv", low_memory=False)
    rows = []
    for cn, label in MARKET.items():
        s = n[n["canonical_name"] == cn]
        for _, r in s.iterrows():
            rows.append({"series": label, "canonical_name": cn, "year": int(r["year"]), "value": r["value"]})
    for cn in H12:
        s = n[n["canonical_name"].astype(str).str.startswith(cn[:60])]
        for _, r in s.iterrows():
            rows.append({"series": "Digital " + ("savings" if "savings" in cn else "credit")
                         + " transactions, value (TZS bn; Table H12, code-extracted D39)", "canonical_name": cn,
                         "year": r["year"], "value": r["value"]})
    m = pd.DataFrame(rows).dropna(subset=["year"])
    m["level"] = "market-level (all institutions; not bank-level)"
    m["evidence_class"] = "Observed"
    return m.sort_values(["series", "year"]).reset_index(drop=True)


