"""Chapter 4.1: revenue architecture (blueprint §4, 4.1; H4.2 different profit engines).

Income composition (net interest vs non-interest income; interest income by source; fees within non-interest income),
growth and volatility, for NMB and CRDB and the seven-bank panel. Inputs: ``data/processed/bank_year_wide.csv``
(detail lines from prompt 03a for NMB and CRDB).
"""

from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

from tzbank.chapters.ch04.common import COLORS, FOCUS, col, div, lag, manifest, note, num, pct, plt_subplots, save, style, tickers, wide
from tzbank.config import find_root, path
from tzbank.extract.detail_lines import NOTES
from tzbank.io import write_csv

SOURCES = ["interest_income_loans", "interest_income_securities", "interest_income_placements",
           "interest_income_other"]
FEES = ["fee_income_transactions", "fee_income_cards", "fee_income_digital", "fee_income_loan_fees",
        "fee_income_fx", "fee_income_other"]


FEE_LABELS = {"fee_income_transactions": "transactions and accounts", "fee_income_cards": "cards",
              "fee_income_digital": "mobile, internet and agency", "fee_income_loan_fees": "loan-related",
              "fee_income_fx": "foreign exchange", "fee_income_other": "other"}
FEE_COLORS = {"fee_income_transactions": "#2a78d6", "fee_income_cards": "#eda100", "fee_income_digital": "#1baf7a",
              "fee_income_loan_fees": "#6250d6", "fee_income_fx": "#e87ba4", "fee_income_other": "#9a9a94"}


def other_fees(root: Path) -> pd.DataFrame:
    """Composition of NMB's 'other' fee type: the printed note lines the D44 mapping leaves uncategorised (blueprint
    §4, 4.1; figure fix prompt 15c). Source: the gated note lines recorded in data/extraction/detail_lines.csv."""
    f = root / "data" / "extraction" / "detail_lines.csv"
    if not f.exists():
        return pd.DataFrame()
    d = pd.read_csv(f)
    d = d[(d["bank_id"] == "B02") & (d["note_kind"] == "fee_income") & (d["variable"] == "Fee Income: Other")]
    rx = [r for _, r in NOTES["fee_income"]["categories"]]
    rows = []
    for r in d.itertuples():
        body = str(r.notes).split("lines: ", 1)[-1].split(" | ")[0]
        printed = re.search(r"printed total ([\d,]+)", str(r.notes))
        unit = float(r.note_total) / float(printed.group(1).replace(",", "")) if printed else 1e6
        for item in body.split("; "):
            lab, _, v = item.rpartition(" ")
            if not lab or any(re.search(x, lab) for x in rx):
                continue
            rows.append({"bank_id": "B02", "fiscal_year": int(r.fiscal_year), "printed_line": lab,
                         "value": float(v.replace(",", "")) * unit, "other_total": float(r.value),
                         "share_of_other": float(v.replace(",", "")) * unit / float(r.value),
                         "note_total": float(r.note_total), "page": r.page, "file": r.file,
                         "evidence_class": "Observed"})
    return pd.DataFrame(rows).sort_values(["fiscal_year", "value"], ascending=[True, False]).reset_index(drop=True)


def composition(w: pd.DataFrame) -> pd.DataFrame:
    nii, nonii = col(w, "net_interest_income"), col(w, "non_interest_income")
    tot = nii + nonii
    out = pd.DataFrame({"bank_id": w["bank_id"], "fiscal_year": w["fiscal_year"], "total_income": tot,
                        "nii_share": div(nii, tot), "nonii_share": div(nonii, tot),
                        "fee_share_of_nonii": div(col(w, "fee_income_total"), nonii),
                        "fee_share_of_income": div(col(w, "fee_income_total"), tot)})
    ii_tot = sum(col(w, c).fillna(0) for c in SOURCES).where(col(w, SOURCES[0]).notna())
    for c in SOURCES:
        out[f"share_{c}"] = div(col(w, c), ii_tot)
    fee_tot = sum(col(w, c).fillna(0) for c in FEES).where(col(w, "fee_income_total").notna())
    for c in FEES:
        out[f"share_{c}"] = div(col(w, c), fee_tot)
    out["fee_type_share_confidence"] = "LOW (label-matched fee types; excluded from 4.7 verdicts)"  # 03b review
    for c, s in [("growth_total_income", tot), ("growth_nii", nii), ("growth_nonii", nonii)]:
        out[c] = div(s, lag(w, s)) - 1
    out["evidence_class"] = "Derived"
    return out


def volatility(comp: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for b, g in comp.groupby("bank_id"):
        for c in ("growth_total_income", "growth_nii", "growth_nonii"):
            s = g[c].dropna()
            rows.append({"bank_id": b, "measure": c, "years": f"{int(g.loc[s.index, 'fiscal_year'].min())}-"
                         f"{int(g.loc[s.index, 'fiscal_year'].max())}" if len(s) else "", "n": len(s),
                         "mean": s.mean(), "std": s.std(), "evidence_class": "Derived"})
    return pd.DataFrame(rows)


NOTE = """# Chapter 4.1: revenue architecture

Generated by `tzbank.chapters.ch04.revenue` (stage `profitability`). Blueprint §4, 4.1; hypothesis H4.2.

## Research question

How does each bank's income split between net interest and non-interest income, which sources drive interest income
and fees, and how fast and how steadily does each component grow?

## Variable definitions

Total income = NII + non-interest income. Interest income by source (loans, government securities,
placements/interbank, other) and fee income by type (transactions and accounts, cards, mobile and internet banking,
loan-related fees, FX, other) come from the notes, extracted in prompt 03a: the lines sum to the printed note total,
which equals the audited interest income within 2% (`data/extraction/detail_lines.csv`). Growth is year on year;
volatility is the standard deviation of growth.

## Sources and transformation trail

`data/processed/bank_year_wide.csv` (inputs workbook, Group, original vintage); functions `composition`,
`volatility`. Tables `outputs/tables/ch04_4_1_composition.csv`, `ch04_4_1_volatility.csv`.

## Validation test

`tests/test_ch04_03a.py`: interest-income and fee components sum to their totals for every bank-year held.

## Results (Derived)

{results}

## Evidence class

Tables and figures: **Derived** (computed from Observed workbook and BoT data); the sector book is
**Observed**. Statements under *Draft interpretation* are **Interpretation**.

## Limitations

- Fee categories are mapped from printed labels; banks label lines differently (e.g. agency and mobile commissions),
  so the split between "transactions" and "mobile and internet banking" is approximate (Interpretation).
  Fee-type shares (including the digital share) are **LOW** confidence and are excluded from every 4.7 verdict until
  the fee-type mapping is verified (03b review).
- Where a note did not reconcile, the year has no split (missing stays missing).
- Non-interest income includes FX, trading and other income besides fees; the fee share isolates fees.

## Interpretation

{interpretation}

## Cross-cutting explanations of rent (blueprint §0)

Fee depth from cards and mobile banking bears on **distribution and market access** and **customer switching
costs**; a stable, deposit-funded interest income bears on **low-cost deposits** (tested in 4.2). Income
volatility in 2015-18 bears on **temporary credit-cycle conditions**.
"""


def write_revenue(root: Path | None = None) -> list[Path]:
    root = root or find_root()
    t = tickers(root)
    w = wide(root)
    comp = composition(w)
    vol = volatility(comp)
    tab, figd = path("tables", root), path("figures", root)
    files = [write_csv(comp, tab / "ch04_4_1_composition.csv", require_evidence=True),
             write_csv(vol, tab / "ch04_4_1_volatility.csv", require_evidence=True)]
    figs = []
    fig, ax = plt_subplots(figsize=(8, 4.4))
    for b in comp["bank_id"].unique():
        d = comp[comp["bank_id"] == b].dropna(subset=["nonii_share"])
        ax.plot(d["fiscal_year"], d["nonii_share"] * 100, color=COLORS.get(b), lw=2 if b in FOCUS else 1,
                marker="o", ms=3, label=t.get(b, b))
    style(ax, "Non-interest income share of total income, seven banks", "percent")
    ax.legend(ncol=7, fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.12))
    png = save(fig, figd / "ch04_4_1_nonii_share.png", "Evidence class: Derived. Non-interest income / (NII + "
               "non-interest income); bank_year_wide.csv.")
    data = write_csv(comp[["bank_id", "fiscal_year", "nonii_share", "evidence_class"]],
                     figd / "ch04_4_1_nonii_share_data.csv", require_evidence=True)
    figs.append({"path": png, "data": data, "description": "Non-interest income share, seven banks",
                 "evidence_class": "Derived"})
    files += [png, data]
    fee = comp[comp["bank_id"].isin(FOCUS)].dropna(subset=["share_fee_income_cards"])
    if len(fee):
        shown = [c for c in FEES if (fee[f"share_{c}"].fillna(0) > 0).any()]  # empty types (e.g. fx) not shown
        fig, axes = plt_subplots(1, 2, figsize=(9, 4.2), sharey=True)
        for ax, b in zip(axes, FOCUS, strict=True):
            d = fee[fee["bank_id"] == b].set_index("fiscal_year")
            bottom = np.zeros(len(d))
            for c in shown:
                v = d[f"share_{c}"].fillna(0).to_numpy() * 100
                ax.bar(d.index, v, bottom=bottom, label=FEE_LABELS[c], color=FEE_COLORS[c], width=0.7)
                bottom += v
            style(ax, f"{t[b]}: fee income by type", "percent of fee income")
        h, lab = axes[0].get_legend_handles_labels()
        fig.legend(h, lab, fontsize=6.5, frameon=False, ncol=len(shown), loc="lower center", bbox_to_anchor=(0.5, 0.035))
        png = save(fig, figd / "ch04_4_1_fee_mix.png", "Evidence class: Derived from Observed note lines (prompt "
                   "03a; CRDB FY2015 and FY2025 prompt 15c; lines sum to the printed fee total). Types: LOW confidence.")
        data = write_csv(fee[["bank_id", "fiscal_year", *[f"share_{c}" for c in FEES], "evidence_class"]],
                         figd / "ch04_4_1_fee_mix_data.csv", require_evidence=True)
        figs.append({"path": png, "data": data, "description": "Fee income by type, NMB and CRDB",
                     "evidence_class": "Derived"})
        files += [png, data]
    oth = other_fees(root)
    if len(oth):
        files.append(write_csv(oth, tab / "ch04_4_1_nmb_other_fees.csv", require_evidence=True))
    f = comp[comp["bank_id"].isin(FOCUS)]
    lines = []
    for b in FOCUS:
        d = f[f["bank_id"] == b].dropna(subset=["nonii_share"])
        if len(d):
            last = d.iloc[-1]
            lines.append(f"- {t[b]} FY{int(last['fiscal_year'])}: non-interest income {pct(last['nonii_share'], 1)} of "
                         f"income; fees {pct(last['fee_share_of_income'], 1)} of income; loans "
                         f"{pct(last['share_interest_income_loans'], 1)} and government securities "
                         f"{pct(last['share_interest_income_securities'], 1)} of interest income.")
        v = vol[(vol["bank_id"] == b) & (vol["measure"] == "growth_total_income")]
        if len(v):
            lines.append(f"  Total-income growth {v['years'].iloc[0]}: mean {pct(v['mean'].iloc[0], 1)}, s.d. "
                         f"{pct(v['std'].iloc[0], 1)}.")
    if len(oth):
        y = int(oth["fiscal_year"].max())
        o = oth[oth["fiscal_year"] == y]
        lines.append(f"- NMB 'other' fees FY{y} ({num(o['other_total'].iloc[0] / 1e9, ',.1f')} bn, "
                     f"{pct(o['other_total'].iloc[0] / o['note_total'].iloc[0], 1)} of gross fees) are the printed lines "
                     + "; ".join(f"{x.printed_line} {pct(x.share_of_other, 0)}" for x in o.itertuples())
                     + ". MNO collaboration fees (mobile-network partnerships) and maintenance fees (account "
                       "maintenance) are not matched by the D44 label rules; reclassifying them to mobile and "
                       "transactions would cut 'other' to the residual 'other fees' line (issue 6; table "
                       "ch04_4_1_nmb_other_fees.csv).")
    interp = ("**Interpretation.** The banks differ more in the composition of interest "
              "income (loans versus securities) and in fee depth than in the NII/non-interest split; 4.0 ranks how "
              "much each difference matters for ROE.")
    nf = note(root, "4.1", NOTE.format(results="\n".join(lines), interpretation=interp))
    tables = [{"path": files[0], "description": "Income composition, interest income by source, fees by type, growth",
               "evidence_class": "Derived"},
              {"path": files[1], "description": "Growth and volatility of income components",
               "evidence_class": "Derived"}]
    if len(oth):
        tables.append({"path": tab / "ch04_4_1_nmb_other_fees.csv",
                       "description": "NMB 'other' fee type: the printed note lines it contains",
                       "evidence_class": "Observed"})
    files += [nf, manifest(root, "4.1", "Revenue architecture", tables, figs, nf, "tzbank.chapters.ch04.revenue",
                           ["data/processed/bank_year_wide.csv"], "built")]
    return files
