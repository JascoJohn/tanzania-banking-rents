"""Chapter 4.5: operating leverage (blueprint §4, 4.5; H4.2; §0 scale economies).

Cost-to-income, OpEx / average assets (identical to the 4.0 tree's opex_ta term), staff cost per employee, assets,
income and profit per employee, branch and agent (KPIs MEDIUM confidence: +/-10% bands), the incremental margin
(Delta income - Delta OpEx) / Delta income, and the scale elasticity: OLS of log OpEx on log average assets per
bank, with a 95% interval. An elasticity below 1 means costs grow more slowly than the balance sheet (scale
economies).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

from tzbank.chapters.ch04.common import (
    COLORS,
    FOCUS,
    avg,
    col,
    div,
    lag,
    manifest,
    note,
    num,
    pct,
    plt_subplots,
    save,
    style,
    tickers,
    wide,
)
from tzbank.config import find_root, path
from tzbank.io import write_csv

KPI_BAND = 0.10


CIR_AXIS_CAP = 1.20  # figure only: values above are drawn at the cap and listed (prompt 15c)


def leverage(w: pd.DataFrame) -> pd.DataFrame:
    income = col(w, "net_interest_income") + col(w, "non_interest_income")
    opex = col(w, "operating_expenses").abs()
    out = pd.DataFrame({"bank_id": w["bank_id"], "fiscal_year": w["fiscal_year"], "total_income": income,
                        "opex": opex})
    out["cost_to_income"] = div(opex, income)
    out["opex_to_avg_assets"] = div(opex, avg(w, "total_assets"))  # = 4.0 opex_ta
    out["staff_share_of_opex"] = div(col(w, "staff_costs"), opex)
    d_inc, d_opex = income - lag(w, income), opex - lag(w, opex)
    out["incremental_margin"] = div(d_inc - d_opex, d_inc)
    for k, c in [("employee", "kpi_employees"), ("branch", "kpi_branches"), ("agent", "kpi_agents")]:
        for m, s in [("assets", col(w, "total_assets")), ("income", income), ("profit", col(w, "net_profit"))]:
            v = div(s, col(w, c))
            out[f"{m}_per_{k}"] = v
            out[f"{m}_per_{k}_low"], out[f"{m}_per_{k}_high"] = v / (1 + KPI_BAND), v / (1 - KPI_BAND)
    out["staff_cost_per_employee"] = div(col(w, "staff_costs"), col(w, "kpi_employees"))
    out["kpi_confidence"] = "MEDIUM (KPIs from narrative pages; +/-10% band)"
    out["evidence_class"] = "Derived"
    return out


def scale_elasticity(w: pd.DataFrame) -> pd.DataFrame:
    rows = []
    ta = avg(w, "total_assets")
    for b in w["bank_id"].unique():
        m = (w["bank_id"] == b) & ta.gt(0) & col(w, "operating_expenses").abs().gt(0)
        x, y = np.log(ta[m]), np.log(col(w, "operating_expenses").abs()[m])
        if len(x) < 5:
            continue
        r = stats.linregress(x, y)
        tcrit = stats.t.ppf(0.975, len(x) - 2)
        rows.append({"bank_id": b, "years": f"{int(w.loc[m, 'fiscal_year'].min())}-{int(w.loc[m, 'fiscal_year'].max())}",
                     "n": len(x), "elasticity": r.slope, "ci_low": r.slope - tcrit * r.stderr,
                     "ci_high": r.slope + tcrit * r.stderr, "r2": r.rvalue ** 2,
                     "reading": "scale economies (CI below 1)" if r.slope + tcrit * r.stderr < 1 else
                     "no evidence of scale economies (CI includes or exceeds 1)", "evidence_class": "Derived"})
    return pd.DataFrame(rows)


