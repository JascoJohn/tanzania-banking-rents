def write_operating_leverage(root: Path | None = None) -> list[Path]:
    root = root or find_root()
    t = tickers(root)
    w = wide(root)
    lev = leverage(w)
    el = scale_elasticity(w)
    tab, figd = path("tables", root), path("figures", root)
    files = [write_csv(lev, tab / "ch04_4_5_operating_leverage.csv", require_evidence=True),
             write_csv(el, tab / "ch04_4_5_scale_elasticity.csv", require_evidence=True)]
    fig, ax = plt_subplots(figsize=(8, 4.4))
    cap = CIR_AXIS_CAP * 100
    above = []
    for b in lev["bank_id"].unique():
        d = lev[lev["bank_id"] == b].dropna(subset=["cost_to_income"])
        y = d["cost_to_income"] * 100
        ax.plot(d["fiscal_year"], y.clip(upper=cap), color=COLORS.get(b), lw=2 if b in FOCUS else 1,
                marker="o", ms=3, label=t.get(b, b))
        hi = d[y > cap]
        if len(hi):
            ax.scatter(hi["fiscal_year"], [cap] * len(hi), marker="^", s=28, color=COLORS.get(b), zorder=3)
            above.append(f"{t.get(b, b)} " + ", ".join(f"FY{int(r.fiscal_year)} {r.cost_to_income:.0%}"
                                                     for r in hi.itertuples()))
    ax.set_ylim(top=cap + 5)
    if above:
        ax.text(0.01, 0.99, "Above the cap (triangles): " + "; ".join(above), transform=ax.transAxes, fontsize=6,
                va="top", color="#5a5a55", wrap=True)
    style(ax, f"Cost-to-income ratio, seven banks (axis capped at {cap:.0f}%)", "percent")
    ax.legend(ncol=7, fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.12))
    png = save(fig, figd / "ch04_4_5_cost_to_income.png", "Evidence class: Derived. OpEx / (NII + non-interest "
               "income). Values above the axis cap are drawn at the cap (triangles) and listed in the panel.")
    data = write_csv(lev[["bank_id", "fiscal_year", "cost_to_income", "evidence_class"]],
                     figd / "ch04_4_5_cost_to_income_data.csv", require_evidence=True)
    figs = [{"path": png, "data": data, "description": "Cost-to-income, seven banks", "evidence_class": "Derived"}]
    files += [png, data]
    lines = []
    for b in FOCUS:
        d = lev[lev["bank_id"] == b].dropna(subset=["cost_to_income"])
        e = el[el["bank_id"] == b]
        if len(d):
            r = d.iloc[-1]
            lines.append(f"- {t[b]} FY{int(r['fiscal_year'])}: cost-to-income {pct(r['cost_to_income'])}, OpEx / avg "
                         f"assets {pct(r['opex_to_avg_assets'], 2)}; mean incremental margin "
                         f"{pct(d['incremental_margin'].clip(-2, 2).median())} (median).")
        if len(e):
            lines.append(f"  Scale elasticity {e['years'].iloc[0]}: {e['elasticity'].iloc[0]:.2f} (95% CI "
                         f"{e['ci_low'].iloc[0]:.2f}-{e['ci_high'].iloc[0]:.2f}): {e['reading'].iloc[0]}.")
        k = lev[(lev["bank_id"] == b)].dropna(subset=["profit_per_employee"])
        if len(k):
            r = k.iloc[-1]
            lines.append(f"  Profit per employee FY{int(r['fiscal_year'])}: TZS {num(r['profit_per_employee'] / 1e6)}m "
                         f"(band {num(r['profit_per_employee_low'] / 1e6)}-{num(r['profit_per_employee_high'] / 1e6)}m;"
                         " MEDIUM).")
    interp = ("**Interpretation.** Falling OpEx / assets was the largest single contributor to "
              "both banks' ROE gains from 2019 to 2025 in the 4.0 attribution; the elasticities say whether that is "
              "scale (cost growing more slowly than assets) or a cyclical squeeze.")
    nf = note(root, "4.5", NOTE.format(results="\n".join(lines), interpretation=interp))
    tables = [{"path": files[0], "description": "Cost ratios, incremental margin, KPI productivity (bands)",
               "evidence_class": "Derived"},
              {"path": files[1], "description": "Scale elasticity of OpEx to assets, per bank (95% CI)",
               "evidence_class": "Derived"}]
    files += [nf, manifest(root, "4.5", "Operating leverage", tables, figs, nf,
                           "tzbank.chapters.ch04.operating_leverage", ["data/processed/bank_year_wide.csv"],
                           "built - KPI ratios MEDIUM confidence")]
    return files
