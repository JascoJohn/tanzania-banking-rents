"""Chapter 4.2: funding economics (blueprint §4, 4.2; §2 gross deposit funding advantage; H4.1; D12 guardrail).

Cost of deposits, deposit mix and the gross deposit funding advantage, GDFA = (y_bill - c_dep) x average deposits,
labelled a **proxy** (D12): it ignores reserve requirements, the operating cost of the deposit franchise, deposit
insurance and asset risk. The net deposit franchise contribution is chapter 6.

y_bill is the annual average of the BoT overall Treasury bill rate (mean of the quarter-end values in
``data/processed/rates_quarterly.csv``, prompt 02f, D40), matching c_dep, which is a flow over average deposits.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from tzbank.chapters.ch04.common import COLORS, FOCUS, avg, col, div, manifest, note, pct, plt_subplots, save, style, tickers, wide
from tzbank.config import find_root, path
from tzbank.io import write_csv

TBILL = "BOTDB_INTEREST_RATES__DOM_TREASURY_BILL_OVERALL_TREASURY_BILL"


def tbill_annual(root: Path) -> pd.Series:
    q = pd.read_csv(path("processed", root) / "rates_quarterly.csv")
    q = q[q["series_id"] == TBILL]
    return q.groupby("year")["value"].mean()


def funding(w: pd.DataFrame, tbill: pd.Series) -> pd.DataFrame:
    dep = avg(w, "customer_deposits")
    out = pd.DataFrame({"bank_id": w["bank_id"], "fiscal_year": w["fiscal_year"], "avg_deposits": dep})
    out["cost_of_deposits"] = div(col(w, "interest_expense_deposits"), dep)
    out["cost_of_funds"] = div(col(w, "interest_expense").abs(),
                               avg(w.assign(_ibl=col(w, "customer_deposits") + col(w, "borrowings").fillna(0)),
                                   "_ibl"))
    tot = col(w, "customer_deposits")
    for c in ("deposits_current", "deposits_savings", "deposits_time"):
        out[f"share_{c}"] = div(col(w, c), tot)
    out["casa_share"] = out["share_deposits_current"] + out["share_deposits_savings"]
    out["deposits_to_liabilities_proxy"] = div(tot, col(w, "total_assets") - col(w, "total_equity"))
    out["tbill_yield_annual_avg"] = out["fiscal_year"].map(tbill)
    out["gdfa_spread"] = out["tbill_yield_annual_avg"] - out["cost_of_deposits"]
    out["gdfa_proxy_tzs"] = out["gdfa_spread"] * dep
    out["gdfa_proxy_to_avg_assets"] = div(out["gdfa_proxy_tzs"], avg(w, "total_assets"))
    out["measure_label"] = "gross deposit funding advantage (proxy, D12); net franchise measure in chapter 6"
    out["evidence_class"] = "Derived"
    return out


NOTE = """# Chapter 4.2: funding economics

Generated by `tzbank.chapters.ch04.funding` (stage `profitability`). Blueprint §4, 4.2; hypothesis H4.1; method
guardrail D12 (CLAUDE.md §8).

## Research question

How cheaply does each bank fund itself, with what deposit mix, and how large is the gross deposit funding advantage?

## Variable definitions

Cost of deposits = interest expense on customer deposits / average customer deposits (reconciled deposit interest,
prompt 02d). Cost of funds = interest expense / average (customer deposits + borrowings). Deposit mix = current,
savings, time / customer deposits. **Gross deposit funding advantage (proxy)** = (y_bill - cost of deposits) x
average deposits, y_bill the annual average of the BoT overall Treasury bill rate. Rent is discussed only with the
net deposit franchise contribution (chapter 6).

## Sources and transformation trail

`data/processed/bank_year_wide.csv`; `data/processed/rates_quarterly.csv` (series `{tbill}`); function `funding`.
Table `outputs/tables/ch04_4_2_funding.csv`.

## Validation test

`tests/test_ch04_03a.py` (GDFA arithmetic on a hand-built case); deposit-interest reconciliation in
`reports/validation/deposit_interest_reconciliation.csv`.

## Results (Derived)

{results}

## Evidence class

Tables and figures: **Derived** (computed from Observed workbook and BoT data); the sector book is
**Observed**. Statements under *Draft interpretation* are **Interpretation**.

## Limitations

- GDFA is a proxy (D12): no reserve requirement cost, no franchise operating cost, no deposit insurance, no asset
  risk. It overstates the economic advantage.
- The T-bill rate is an annual average of quarter-end values, not of auctions.
- Deposit mix for CRDB is held only where the note was found (prompt 02b/02e/03a); gaps stay gaps.

## Interpretation

{interpretation}

## Cross-cutting explanations of rent (blueprint §0)

Supports or contradicts **low-cost deposits** (cost of deposits, CASA share) and **distribution and market
access** (branch and agent reach behind cheap deposits). The proxy cannot separate a structural franchise from
**limited competition**; chapter 6 tests this.
"""


def write_funding(root: Path | None = None) -> list[Path]:
    root = root or find_root()
    t = tickers(root)
    f = funding(wide(root), tbill_annual(root))
    tab, figd = path("tables", root), path("figures", root)
    files = [write_csv(f, tab / "ch04_4_2_funding.csv", require_evidence=True)]
    fig, ax = plt_subplots(figsize=(8, 4.4))
    for b in f["bank_id"].unique():
        d = f[f["bank_id"] == b].dropna(subset=["cost_of_deposits"])
        ax.plot(d["fiscal_year"], d["cost_of_deposits"] * 100, color=COLORS.get(b), lw=2 if b in FOCUS else 1,
                marker="o", ms=3, label=t.get(b, b))
    tb = f.drop_duplicates("fiscal_year").dropna(subset=["tbill_yield_annual_avg"]).sort_values("fiscal_year")
    ax.plot(tb["fiscal_year"], tb["tbill_yield_annual_avg"] * 100, color="#5a5a55", ls="--", lw=1.2,
            label="T-bill (annual avg)")
    style(ax, "Cost of deposits vs Treasury bill yield", "percent")
    ax.legend(ncol=4, fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.12))
    png = save(fig, figd / "ch04_4_2_cost_of_deposits.png", "Evidence class: Derived. Cost of deposits = deposit "
               "interest / average deposits; T-bill = BoT overall rate, annual average of quarter-ends.")
    data = write_csv(f[["bank_id", "fiscal_year", "cost_of_deposits", "tbill_yield_annual_avg", "evidence_class"]],
                     figd / "ch04_4_2_cost_of_deposits_data.csv", require_evidence=True)
    figs = [{"path": png, "data": data, "description": "Cost of deposits and T-bill yield",
             "evidence_class": "Derived"}]
    files += [png, data]
    lines = []
    for b in FOCUS:
        d = f[f["bank_id"] == b].dropna(subset=["gdfa_proxy_to_avg_assets"])
        if len(d):
            r = d.iloc[-1]
            lines.append(f"- {t[b]} FY{int(r['fiscal_year'])}: cost of deposits {pct(r['cost_of_deposits'], 2)}, T-bill "
                         f"{pct(r['tbill_yield_annual_avg'], 2)}, GDFA proxy {r['gdfa_proxy_tzs'] / 1e9:,.0f}bn "
                         f"({pct(r['gdfa_proxy_to_avg_assets'], 2)} of average assets); CASA share "
                         f"{pct(r['casa_share'], 1)}." if pd.notna(r["casa_share"]) else
                         f"- {t[b]} FY{int(r['fiscal_year'])}: cost of deposits {pct(r['cost_of_deposits'], 2)}; GDFA "
                         f"proxy {pct(r['gdfa_proxy_to_avg_assets'], 2)} of average assets.")
            lines.append(f"  Mean cost of deposits {d['fiscal_year'].min()}-{d['fiscal_year'].max()}: "
                         f"{pct(d['cost_of_deposits'].mean(), 2)}.")
    interp = ("**Interpretation.** A lower cost of deposits at NMB than at CRDB is the funding "
              "leg of H4.1; 4.0 shows how much of the ROE gap it carries. The proxy is an upper bound on the "
              "advantage; rent claims wait for the net franchise measure (chapter 6).")
    nf = note(root, "4.2", NOTE.format(tbill=TBILL, results="\n".join(lines), interpretation=interp))
    tables = [{"path": files[0], "description": "Cost of deposits and funds, deposit mix, gross deposit funding "
               "advantage (proxy, D12)", "evidence_class": "Derived"}]
    files += [nf, manifest(root, "4.2", "Funding economics", tables, figs, nf, "tzbank.chapters.ch04.funding",
                           ["data/processed/bank_year_wide.csv", "data/processed/rates_quarterly.csv"],
                           "built - GDFA is a proxy")]
    return files
