"""Chapter 4.6: risk economics (blueprint §4, 4.6; H4.2; chapter 8 goes deeper).

Business-model level only: cost of risk = impairment / average gross loans (blueprint §2); NPL ratio = stage-3 gross
loans / gross loans; coverage = loss allowance / stage-3 loans; NIM = NII / average interest-earning assets
(average total assets where IEA is not held, flagged); risk-adjusted NIM = NIM - cost of risk; return on RWA = net
profit / average RWA. The impairment term equals the 4.0 tree's imp_ta after rescaling by gross loans / assets.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from tzbank.chapters.ch04.common import COLORS, FOCUS, avg, col, div, manifest, note, pct, plt_subplots, save, style, tickers, wide
from tzbank.config import find_root, path
from tzbank.io import write_csv


def risk(w: pd.DataFrame) -> pd.DataFrame:
    imp = col(w, "impairment_charges").abs()
    out = pd.DataFrame({"bank_id": w["bank_id"], "fiscal_year": w["fiscal_year"]})
    out["cost_of_risk"] = div(imp, avg(w, "gross_loans"))
    out["npl_ratio"] = div(col(w, "stage3_loans_gross"), col(w, "gross_loans"))
    out["coverage"] = div(col(w, "loan_loss_allowance").abs(), col(w, "stage3_loans_gross"))
    iea = avg(w, "interest_earning_assets")
    nii = col(w, "net_interest_income")
    out["nim"] = div(nii, iea).fillna(div(nii, avg(w, "total_assets")))
    out["nim_basis"] = iea.notna().map({True: "NII / avg IEA", False: "NII / avg total assets (IEA not held)"})
    out["risk_adjusted_nim"] = out["nim"] - out["cost_of_risk"]
    out["return_on_rwa"] = div(col(w, "net_profit"), avg(w, "rwa_total"))
    out["impairment_to_avg_assets"] = div(imp, avg(w, "total_assets"))  # = 4.0 imp_ta
    out["evidence_class"] = "Derived"
    return out[out[["cost_of_risk", "nim", "return_on_rwa"]].notna().any(axis=1)].reset_index(drop=True)


