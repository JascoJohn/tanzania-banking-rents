def with_capital_basis_rwa(w: pd.DataFrame, root: Path) -> pd.DataFrame:
    """NMB / CRDB RWA on the D2/D17 capital basis (as chapters 7 and 8; prompt 08 consistency fix): NMB Bank-solo,
    CRDB Bank-solo to FY2014 and Group from FY2015. Other banks keep the reported RWA."""
    from tzbank.chapters.ch07_capital import capital_basis

    cb = capital_basis(root)
    cb = cb.assign(fiscal_year=cb["fiscal_year"].astype(int)).set_index(["bank_id", "fiscal_year"])["rwa_total"]
    w = w.copy()
    key = list(zip(w["bank_id"], w["fiscal_year"].astype(int), strict=True))
    foc = w["bank_id"].isin(FOCUS)
    w.loc[foc, "rwa_total"] = [cb.get(k, float("nan")) for k, f in zip(key, foc, strict=True) if f]
    return w


def write_risk(root: Path | None = None) -> list[Path]:
    root = root or find_root()
    t = tickers(root)
    r = risk(with_capital_basis_rwa(wide(root), root))
    tab, figd = path("tables", root), path("figures", root)
    files = [write_csv(r, tab / "ch04_4_6_risk.csv", require_evidence=True)]
    fig, ax = plt_subplots(figsize=(8, 4.4))
    for b in FOCUS:
        d = r[r["bank_id"] == b]
        ax.plot(d["fiscal_year"], d["cost_of_risk"] * 100, color=COLORS[b], lw=2, marker="o", ms=3,
                label=f"{t[b]} cost of risk")
        ax.plot(d["fiscal_year"], d["risk_adjusted_nim"] * 100, color=COLORS[b], lw=1, ls="--",
                label=f"{t[b]} risk-adjusted NIM")
    style(ax, "Cost of risk and risk-adjusted NIM, NMB and CRDB", "percent")
    ax.legend(ncol=2, fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.12))
    png = save(fig, figd / "ch04_4_6_risk.png", "Evidence class: Derived. Cost of risk = impairment / avg gross loans;"
               " risk-adjusted NIM = NII / avg IEA - cost of risk.")
    data = write_csv(r[r["bank_id"].isin(FOCUS)][["bank_id", "fiscal_year", "cost_of_risk", "risk_adjusted_nim",
                                                  "evidence_class"]], figd / "ch04_4_6_risk_data.csv",
                     require_evidence=True)
    figs = [{"path": png, "data": data, "description": "Cost of risk and risk-adjusted NIM",
             "evidence_class": "Derived"}]
    files += [png, data]
    lines = []
    for b in FOCUS:
        d = r[r["bank_id"] == b]
        if len(d):
            x = d.iloc[-1]
            stress = d[d["fiscal_year"].between(2015, 2018)]["cost_of_risk"].mean()
            lines.append(f"- {t[b]} FY{int(x['fiscal_year'])}: cost of risk {pct(x['cost_of_risk'], 2)} (2015-18 mean "
                         f"{pct(stress, 2)}), NPL ratio {pct(x['npl_ratio'])}, coverage {pct(x['coverage'], 0)}, "
                         f"risk-adjusted NIM {pct(x['risk_adjusted_nim'], 2)}, return on RWA "
                         f"{pct(x['return_on_rwa'], 2)}.")
    interp = ("**Interpretation.** Impairment explains much of CRDB's 2015-18 trough and its "
              "recovery (4.0); NMB's higher NIM leaves a wider buffer after credit costs. Whether today's low cost of "
              "risk is durable is a chapter 8 question.")
    nf = note(root, "4.6", NOTE.format(results="\n".join(lines), interpretation=interp))
    tables = [{"path": files[0], "description": "Cost of risk, NPLs, coverage, risk-adjusted NIM, return on RWA",
               "evidence_class": "Derived"}]
    files += [nf, manifest(root, "4.6", "Risk economics", tables, figs, nf, "tzbank.chapters.ch04.risk",
                           ["data/processed/bank_year_wide.csv"],
                           "built - business-model level")]
    return files
